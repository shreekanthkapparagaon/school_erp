from decimal import Decimal
from decimal import InvalidOperation

from django.core.exceptions import ValidationError
from django.db import transaction

from openpyxl import load_workbook

from apps.accounts.models import User
from apps.schools.models import Subject

from ..models import Result
from .excel_constants import HEADER_ROW

def import_result_workbook(
    *,
    file,
    exam,
    school_class,
    imported_by,
):
    """
    Import results from a workbook generated by
    generate_result_import_template().
    """

    workbook = load_workbook(file)

    imported = 0

    with transaction.atomic():

        # ------------------------------------
        # Prepare Exam
        # ------------------------------------

        if not exam.classes.filter(
            pk=school_class.pk
        ).exists():
            exam.classes.add(school_class)

        if not exam.can_enter_results:
            raise ValidationError(  
                "Results can only be imported while the examination is active."
            )

        # ------------------------------------
        # Every worksheet = one subject
        # ------------------------------------

        for worksheet in workbook.worksheets:

            subject_code = worksheet["D3"].value

            if not subject_code:
                raise ValidationError(
                    f"{worksheet.title}: Subject code missing."
                )

            try:

                subject = Subject.objects.get(
                    school=school_class.school,
                    code=subject_code,
                )

            except Subject.DoesNotExist:

                raise ValidationError(
                    f"Unknown subject code '{subject_code}'."
                )

            # --------------------------------

            row = HEADER_ROW + 1

            while True:

                username = worksheet.cell(
                    row=row,
                    column=1,
                ).value

                if username in (
                    None,
                    "",
                ):
                    break

                marks = worksheet.cell(
                    row=row,
                    column=3,
                ).value

                maximum = worksheet.cell(
                    row=row,
                    column=4,
                ).value

                if marks in (
                    None,
                    "",
                ):
                    row += 1
                    continue

                try:

                    marks = Decimal(
                        str(marks)
                    )

                    maximum = Decimal(
                        str(maximum)
                    )

                except (
                    InvalidOperation,
                    TypeError,
                ):

                    raise ValidationError(
                        f"{worksheet.title} "
                        f"Row {row}: "
                        "Invalid marks."
                    )

                try:

                    student = User.objects.get(
                        school=school_class.school,
                        school_class=school_class,
                        role=User.Role.STUDENT,
                        username=username,
                    )

                except User.DoesNotExist:

                    raise ValidationError(
                        f"{worksheet.title} "
                        f"Row {row}: "
                        f"Student '{username}' "
                        "does not exist."
                    )

                result = Result.objects.filter(
                    school_class=school_class,
                    student=student,
                    subject=subject,
                    exam=exam,
                ).first()

                if result is None:

                    result = Result(
                        school=school_class.school,
                        school_class=school_class,
                        student=student,
                        subject=subject,
                        exam=exam,
                        created_by=imported_by,
                    )

                result.marks_obtained = marks
                result.max_marks = maximum

                result.full_clean()
                result.save()

                imported += 1

                row += 1

    return imported